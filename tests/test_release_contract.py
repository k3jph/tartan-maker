"""Release metadata and documented installation examples must remain usable."""

from __future__ import annotations

from pathlib import Path
import re
import tomllib

import pytest

from tartan_maker import __version__, load_spec, render_svg


ROOT = Path(__file__).resolve().parents[1]


def test_project_version_matches_public_api() -> None:
    metadata = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    assert metadata["project"]["name"] == "tartan-maker"
    assert metadata["project"]["version"] == __version__
    assert metadata["project"]["requires-python"] == ">=3.11"


@pytest.mark.parametrize(
    "name",
    [
        "black-watch.yaml",
        "balmoral.yaml",
        "rob-roy-macgregor.yaml",
        "buchanan.yaml",
        "royal-stewart.yaml",
        "macleod-of-lewis.yaml",
    ],
)
def test_repository_examples_render(name: str) -> None:
    spec = load_spec(ROOT / "examples" / name)
    svg = render_svg(spec)
    assert '<svg xmlns="http://www.w3.org/2000/svg"' in svg
    assert "Generated by tartan-maker " + __version__ in svg


def test_installed_cli_quickstart_example(tmp_path: Path) -> None:
    text = (ROOT / "docs" / "quickstart.md").read_text(encoding="utf-8")
    match = re.search(r"```yaml\n(.*?)\n```", text, flags=re.DOTALL)
    assert match is not None, "quickstart needs an inline YAML spec"
    path = tmp_path / "my-tartan.yaml"
    path.write_text(match.group(1), encoding="utf-8")
    assert "<svg" in render_svg(load_spec(path))
